const STORAGE_KEY = 'language'

const I18nContext = createContext<I18nContextType | undefined>(undefined)

export const useI18n = () => {
  const context = useContext(I18nContext)
  if (context === undefined) {
    throw new Error('useI18n must be used within an I18nProvider')
  }
  return context
}

const readInitialLanguage = (): Language => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'ar' || saved === 'en' || saved === 'fr') return saved
  } catch {
    // localStorage unavailable
  }
  return 'ar'
}

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(readInitialLanguage)
  const dir: 'rtl' | 'ltr' = language === 'ar' ? 'rtl' : 'ltr'

  useEffect(() => {
    const root = document.documentElement
    root.lang = language
    root.dir = dir
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // ignore storage errors
    }
  }, [language, dir])

  const setLanguage = (lang: Language) => setLanguageState(lang)

  const t = (key: string, vars?: Record<string, string | number>): string => {
    const current = translations[language] as Record<string, string>
    const fallback = translations.ar as Record<string, string>
    let value = current[key] ?? fallback[key] ?? key
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.split(`{${name}}`).join(String(replacement))
      }
    }
    return value
  }

  return (
    <I18nContext.Provider value={{ language, dir, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  )
}
